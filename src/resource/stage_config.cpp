	foo::GridConfig CombineGrid(char* out, const char* tiles, const char* space_a, const char* space_b, int area_id)
	{
		foo::GridConfig config{};
		config.tiles = out;
		config.scope_id = area_id;
		int fan_cnt{ 0 }, enemy_cnt{ 0 };
		for (int i = 0; i < foo::GridConfig::TILE_CNT; i++)
		{
			int col = i % foo::GridConfig::TILE_COLS;
			int row = i / foo::GridConfig::TILE_COLS;
			out[i] = 0;
			if (tiles[i] != '0')
			{
				if (tiles[i] == '$' || tiles[i] == '%' || tiles[i] == '^' || tiles[i] == '&')
				{
					config.item = tiles[i];
					config.item_index = i;
				}
				else if (tiles[i] == 'a')
				{
					if (col == 0 || tiles[i - 1] != 'a')
					{
						int width{ 0 }, height{ 0 };
						while (col + width < foo::GridConfig::TILE_COLS && tiles[i + width] == 'a')
						{
							width++;
						}
						while (row + height < foo::GridConfig::TILE_ROWS && tiles[i + row * foo::GridConfig::TILE_COLS] != '1')
						{
							height++;
						}
						config.rain_config[config.rain_cnt] = { width, height, i };
						config.rain_cnt++;
					}
				}
				else if (tiles[i] == 'R')
				{
					config.save_point = i;
				}
				else if (tiles[i] == 'f')
				{
					if (col > 0 && tiles[i - 1] == 'f')
					{
						config.fan_point[fan_cnt] = i - 0.5f;
					}
					else
					{
						config.fan_point[fan_cnt++] = i;
					}					
				}
				else if (tiles[i] == 'e')
				{
					config.enemy_point[enemy_cnt++] = i;
				}
				else
				{
					out[i] |= 1;
				}
			}
			if (space_a[i] != '0')
			{
				out[i] |= 2;
			}
			if (space_b[i] != '0')
			{
				out[i] |= 4;
			}
		}
		// last guard
		if (fan_cnt < foo::GridConfig::MAX_FAN)
		{
			config.fan_point[fan_cnt] = -1;
		}
		if (enemy_cnt < foo::GridConfig::MAX_ENEMY)
		{
			config.enemy_point[enemy_cnt] = -1;
		}
		return config;
	}
